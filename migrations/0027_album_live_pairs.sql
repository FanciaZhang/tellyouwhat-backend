-- Final JPEG/MOV bytes have their own escrow. They cannot reuse a closed
-- component budget or masquerade as another original backup.
CREATE TABLE IF NOT EXISTS album_live_pairs (
    pair_upload_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    owner_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    asset_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    manifest_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    preset VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    active_preset VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    descriptor_json JSON NOT NULL,
    source_photo_json JSON NOT NULL,
    source_video_json JSON NOT NULL,
    objects_json JSON NOT NULL,
    size_bytes BIGINT NOT NULL,
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'uploading',
    photo_consumed BOOLEAN NOT NULL DEFAULT FALSE,
    movie_consumed BOOLEAN NOT NULL DEFAULT FALSE,
    expires_at DATETIME(6) NOT NULL,
    available_at DATETIME(6) NOT NULL,
    lease_token CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    lease_until DATETIME(6) NULL,
    attempts INT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    UNIQUE KEY album_live_pair_request (owner_id, request_id),
    UNIQUE KEY album_live_pair_active (owner_id, version_id, active_preset),
    KEY album_live_pair_ready (state, available_at, lease_until),
    CONSTRAINT album_live_pair_source_fk FOREIGN KEY (owner_id, version_id) REFERENCES album_asset_versions(owner_id, version_id),
    CHECK (preset='daily_live_pair_v1'),
    CHECK (active_preset IS NULL OR active_preset=preset),
    CHECK (state IN ('uploading','queued','verifying','verified','attention','retiring','retired')),
    CHECK ((state='retired' AND active_preset IS NULL) OR (state<>'retired' AND active_preset IS NOT NULL)),
    CHECK (size_bytes > 0 AND size_bytes <= 4311744512),
    CHECK (attempts >= 0 AND attempts <= 8)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
