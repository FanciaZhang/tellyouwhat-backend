CREATE TABLE album_push_registrations (
    registration_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    session_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    environment VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'disabled',
    revision BIGINT NOT NULL DEFAULT 0,
    token_sha256 BINARY(32) NULL,
    encrypted_token BLOB NULL,
    token_nonce BINARY(12) NULL,
    registered_at DATETIME(6) NULL,
    request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    request_sha256 BINARY(32) NULL,
    UNIQUE KEY album_push_session(session_id,environment),
    UNIQUE KEY album_push_token(environment,token_sha256),
    CONSTRAINT album_push_session_fk FOREIGN KEY(session_id) REFERENCES album_sessions(session_id),
    CHECK(environment IN ('development','production')),
    CHECK(state IN ('enabled','disabled','superseded')),
    CHECK(revision >= 0),
    CHECK((encrypted_token IS NULL) = (token_nonce IS NULL)),
    CHECK((state='enabled') = (encrypted_token IS NOT NULL)),
    CHECK(state<>'enabled' OR (token_sha256 IS NOT NULL AND registered_at IS NOT NULL)),
    CHECK(state<>'superseded' OR token_sha256 IS NULL),
    CHECK((request_id IS NULL) = (request_sha256 IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
