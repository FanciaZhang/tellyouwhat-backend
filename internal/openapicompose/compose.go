package openapicompose

import (
	"bytes"
	"context"
	"errors"
	"fmt"

	"github.com/getkin/kin-openapi/openapi3"
	"gopkg.in/yaml.v3"
)

// Compose produces one self-contained public contract from the canonical
// platform contract and one App-specific contract while preserving the source
// order that determines generated Swift initializer signatures.
func Compose(platformSource, appSource []byte) ([]byte, error) {
	platform, err := decode(platformSource)
	if err != nil {
		return nil, fmt.Errorf("decode platform contract: %w", err)
	}
	app, err := decode(appSource)
	if err != nil {
		return nil, fmt.Errorf("decode App contract: %w", err)
	}

	result := cloneNode(app)
	platformRoot := documentRoot(platform)
	resultRoot := documentRoot(result)
	if err := mergeNamedMapping(resultRoot, platformRoot, "paths"); err != nil {
		return nil, err
	}
	if err := mergeComponents(resultRoot, platformRoot); err != nil {
		return nil, err
	}
	if err := mergeTags(resultRoot, platformRoot); err != nil {
		return nil, err
	}

	var encoded bytes.Buffer
	encoded.WriteString("# Code generated by openapi-compose. DO NOT EDIT.\n")
	encoder := yaml.NewEncoder(&encoded)
	encoder.SetIndent(2)
	if err := encoder.Encode(result); err != nil {
		return nil, fmt.Errorf("encode composed contract: %w", err)
	}
	if err := encoder.Close(); err != nil {
		return nil, fmt.Errorf("close composed contract encoder: %w", err)
	}
	output := encoded.Bytes()
	if err := validate(output); err != nil {
		return nil, err
	}
	return output, nil
}

func decode(source []byte) (*yaml.Node, error) {
	var document yaml.Node
	if err := yaml.Unmarshal(source, &document); err != nil {
		return nil, err
	}
	root := documentRoot(&document)
	if root == nil || root.Kind != yaml.MappingNode {
		return nil, errors.New("contract root is not a mapping")
	}
	for _, required := range []string{"openapi", "info", "paths"} {
		if _, _, ok := mappingEntry(root, required); !ok {
			return nil, fmt.Errorf("contract is missing %s", required)
		}
	}
	return &document, nil
}

func documentRoot(document *yaml.Node) *yaml.Node {
	if document == nil || document.Kind != yaml.DocumentNode || len(document.Content) != 1 {
		return nil
	}
	return document.Content[0]
}

func cloneNode(source *yaml.Node) *yaml.Node {
	if source == nil {
		return nil
	}
	result := *source
	result.Content = make([]*yaml.Node, len(source.Content))
	for index, child := range source.Content {
		result.Content[index] = cloneNode(child)
	}
	return &result
}

func mappingEntry(mapping *yaml.Node, name string) (*yaml.Node, *yaml.Node, bool) {
	if mapping == nil || mapping.Kind != yaml.MappingNode {
		return nil, nil, false
	}
	for index := 0; index+1 < len(mapping.Content); index += 2 {
		if mapping.Content[index].Value == name {
			return mapping.Content[index], mapping.Content[index+1], true
		}
	}
	return nil, nil, false
}

func mergeNamedMapping(targetRoot, sourceRoot *yaml.Node, field string) error {
	_, targetValues, targetExists := mappingEntry(targetRoot, field)
	sourceKey, sourceValues, sourceExists := mappingEntry(sourceRoot, field)
	if !sourceExists || sourceValues.Kind != yaml.MappingNode {
		return fmt.Errorf("platform contract %s is not a mapping", field)
	}
	if !targetExists {
		targetRoot.Content = append(targetRoot.Content, cloneNode(sourceKey), cloneNode(sourceValues))
		return nil
	}
	if targetValues.Kind != yaml.MappingNode {
		return fmt.Errorf("App contract %s is not a mapping", field)
	}
	if err := rejectMappingCollisions(targetValues, sourceValues, field+" entry "); err != nil {
		return err
	}
	platformContent := cloneNode(sourceValues).Content
	targetValues.Content = append(platformContent, targetValues.Content...)
	return nil
}

func mergeComponents(targetRoot, sourceRoot *yaml.Node) error {
	_, targetComponents, targetExists := mappingEntry(targetRoot, "components")
	sourceKey, sourceComponents, sourceExists := mappingEntry(sourceRoot, "components")
	if !sourceExists || sourceComponents.Kind != yaml.MappingNode {
		return errors.New("platform contract components is not a mapping")
	}
	if !targetExists {
		targetRoot.Content = append(targetRoot.Content, cloneNode(sourceKey), cloneNode(sourceComponents))
		return nil
	}
	if targetComponents.Kind != yaml.MappingNode {
		return errors.New("App contract components is not a mapping")
	}
	for index := 0; index+1 < len(sourceComponents.Content); index += 2 {
		categoryKey := sourceComponents.Content[index]
		sourceValues := sourceComponents.Content[index+1]
		_, targetValues, exists := mappingEntry(targetComponents, categoryKey.Value)
		if !exists {
			targetComponents.Content = append(targetComponents.Content, cloneNode(categoryKey), cloneNode(sourceValues))
			continue
		}
		if sourceValues.Kind != yaml.MappingNode || targetValues.Kind != yaml.MappingNode {
			return fmt.Errorf("component category %q is not a mapping", categoryKey.Value)
		}
		if err := rejectMappingCollisions(targetValues, sourceValues, "component "+categoryKey.Value+"/"); err != nil {
			return err
		}
		platformContent := cloneNode(sourceValues).Content
		targetValues.Content = append(platformContent, targetValues.Content...)
	}
	return nil
}

func rejectMappingCollisions(left, right *yaml.Node, label string) error {
	seen := make(map[string]struct{}, len(left.Content)/2)
	for index := 0; index+1 < len(left.Content); index += 2 {
		seen[left.Content[index].Value] = struct{}{}
	}
	for index := 0; index+1 < len(right.Content); index += 2 {
		name := right.Content[index].Value
		if _, exists := seen[name]; exists {
			return fmt.Errorf("duplicate %s%q", label, name)
		}
	}
	return nil
}

func mergeTags(targetRoot, sourceRoot *yaml.Node) error {
	_, targetTags, targetExists := mappingEntry(targetRoot, "tags")
	sourceKey, sourceTags, sourceExists := mappingEntry(sourceRoot, "tags")
	if !sourceExists {
		return nil
	}
	if sourceTags.Kind != yaml.SequenceNode {
		return errors.New("platform contract tags is not a sequence")
	}
	if !targetExists {
		targetRoot.Content = append(targetRoot.Content, cloneNode(sourceKey), cloneNode(sourceTags))
		return nil
	}
	if targetTags.Kind != yaml.SequenceNode {
		return errors.New("App contract tags is not a sequence")
	}
	seen := make(map[string]struct{})
	for _, tag := range targetTags.Content {
		if name := tagName(tag); name != "" {
			seen[name] = struct{}{}
		}
	}
	platformTags := make([]*yaml.Node, 0, len(sourceTags.Content))
	for _, tag := range sourceTags.Content {
		name := tagName(tag)
		if _, exists := seen[name]; name != "" && exists {
			continue
		}
		platformTags = append(platformTags, cloneNode(tag))
	}
	targetTags.Content = append(platformTags, targetTags.Content...)
	return nil
}

func tagName(tag *yaml.Node) string {
	_, value, ok := mappingEntry(tag, "name")
	if !ok || value.Kind != yaml.ScalarNode {
		return ""
	}
	return value.Value
}

func validate(source []byte) error {
	loader := openapi3.NewLoader()
	document, err := loader.LoadFromData(source)
	if err != nil {
		return fmt.Errorf("load composed contract: %w", err)
	}
	if err := document.Validate(context.Background()); err != nil {
		return fmt.Errorf("validate composed contract: %w", err)
	}
	return nil
}

// Equal reports whether two generated contracts are byte-for-byte equal after
// normalizing surrounding whitespace.
func Equal(left, right []byte) bool {
	return bytes.Equal(bytes.TrimSpace(left), bytes.TrimSpace(right))
}
